-- Run once per environment by the DBA, connected to the QualityContext database as the Entra SQL
-- administrator (not as the runtime identity).
--
-- Deviation from the portfolio default: RPA.QualityPortal's QualityContext is an EF6 Code-First
-- context hard-wired to the classic System.Data.SqlClient ADO.NET provider (see
-- DAL/QualityDbConfiguration.cs). Microsoft never shipped a stable EF6 provider for
-- Microsoft.Data.SqlClient, so passwordless Entra/managed-identity SQL authentication (the pattern
-- used by this portfolio's other apps, e.g. "CREATE USER ... FROM EXTERNAL PROVIDER") is not
-- available until a future EF Core migration (tracked as a follow-up, not a blocker - see the
-- application README). This script instead creates a SQL-authentication contained database user.
-- The foundation's main.bicep deliberately sets azureADOnlyAuthentication=false to allow this.
--
-- Replace the placeholders with the runtime SQL-authentication username and a strong, unique
-- password generated by the DBA. Store that exact username/password pair as the full
-- ConnectionStrings:QualityContext connection string in the Key Vault secret referenced by
-- app.bicep's qualityConnectionStringSecretName parameter (e.g.
-- "Server=tcp:<sql-server-fqdn>,1433;Initial Catalog=<databaseName>;User ID=<username>;
--  Password=<password>;Encrypt=True;TrustServerCertificate=False;").

DECLARE @username sysname = N'<quality-app-sql-username>';
DECLARE @password nvarchar(128) = N'<quality-app-sql-password>';

IF @username = N'<quality-app-sql-username>' OR @password = N'<quality-app-sql-password>'
    THROW 50000, 'Replace both placeholders before running this script.', 1;

DECLARE @sql nvarchar(max);

IF NOT EXISTS (SELECT 1 FROM sys.database_principals WHERE name = @username)
BEGIN
    SET @sql = N'CREATE USER ' + QUOTENAME(@username) + N' WITH PASSWORD = ' + QUOTENAME(@password, '''') + N';';
    EXEC (@sql);
END
ELSE
BEGIN
    -- Rerunning this script must not silently skip a required rotation.
    SET @sql = N'ALTER USER ' + QUOTENAME(@username) + N' WITH PASSWORD = ' + QUOTENAME(@password, '''') + N';';
    EXEC (@sql);
END

SET @sql = N'ALTER ROLE db_datareader ADD MEMBER ' + QUOTENAME(@username) + N';';
EXEC (@sql);

SET @sql = N'ALTER ROLE db_datawriter ADD MEMBER ' + QUOTENAME(@username) + N';';
EXEC (@sql);

-- The application reads and writes data only. Do not add db_owner or db_ddladmin.
-- Readiness checks (SELECT 1) and the EF6 migration runner (ApplyMigrationsOnStartup/DbMigrator,
-- run separately by the deployment pipeline, not by this script) need no extra permission beyond
-- db_datareader/db_datawriter plus whatever the pipeline's own migration identity already has.

-- Verify: the user is a member of exactly the two data roles.
SELECT r.name AS role_name
FROM sys.database_role_members m
JOIN sys.database_principals r ON r.principal_id = m.role_principal_id
JOIN sys.database_principals u ON u.principal_id = m.member_principal_id
WHERE u.name = @username
ORDER BY r.name;